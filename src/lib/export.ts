import { COMPANY, PRICING_BASIS } from '../config/company';
import { getDeparture, mustDestination } from '../data/catalog';
import type { Estimate } from './estimate';
import { layoutDay } from './itinerary';
import { fmtDate, fmtTime } from './time';
import type { DayPlan, TripConfig } from './trip';

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);

/** Standalone, printable HTML itinerary branded as Travel Guide. */
export function itineraryHTML(name: string, c: TripConfig, days: DayPlan[], est: Estimate, money: (n: number) => string) {
  const dests = [...new Set(days.map((d) => mustDestination(d.destId).name))].join(', ');
  const dayHtml = days.map((day) => {
    const l = layoutDay(day, c);
    const rows = l.rows.map((r) => `
      <tr><td class="t">${fmtTime(r.start)}–${fmtTime(r.end)}</td>
      <td><strong>${esc(r.item.title)}</strong>${r.item.during ? ' <em>(during previous)</em>' : ''}<br><span class="m">${esc(r.item.location)}${r.transferBefore ? ` · ${r.transferBefore} min transfer before` : ''}${r.item.note ? ` · ${esc(r.item.note)}` : ''}</span>
      ${r.issues.map((i) => `<div class="w">⚠ ${esc(i.text)}</div>`).join('')}</td>
      <td class="c">${r.item.groupCost || r.item.costPP ? money((r.item.groupCost ?? 0) + r.item.costPP * (c.adults + c.children * 0.5)) : '—'}</td></tr>`).join('');
    const dc = est.daily.find((x) => x.index === day.index);
    return `<section><h2>Day ${day.index + 1} · ${esc(fmtDate(day.date))} — ${esc(day.title)}</h2>
      <p class="m">Approx. sunrise ${fmtTime(l.sunrise)} · sunset ${fmtTime(l.sunset)} · day estimate ${dc ? money(dc.total) : '—'}</p>
      <table>${rows}</table></section>`;
  }).join('');
  const cats = est.categories.filter((x) => x.amount > 0 || x.key === 'fees').map((x) => `<tr><td>${x.label}</td><td class="c">${money(x.amount)}</td></tr>`).join('');
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(name)} — ${COMPANY.name}</title>
<style>body{font-family:Inter,system-ui,sans-serif;color:#13201c;max-width:860px;margin:2rem auto;padding:0 1rem;line-height:1.45}
h1{font-family:Georgia,serif;margin:.2rem 0}h2{font-family:Georgia,serif;font-size:1.15rem;margin:1.6rem 0 .3rem;border-top:1px solid #cfd8d4;padding-top:1rem}
table{width:100%;border-collapse:collapse}td{padding:.4rem .3rem;vertical-align:top;border-bottom:1px solid #eef2f0}.t{white-space:nowrap;width:7.5rem;font-variant-numeric:tabular-nums}.c{text-align:right;white-space:nowrap}
.m{color:#55665f;font-size:.86rem}.w{color:#9a4a00;font-size:.84rem}.brand{display:flex;justify-content:space-between;align-items:baseline;border-bottom:2px solid #0d2a22;padding-bottom:.5rem}
.note{background:#f3f6f4;padding:.8rem 1rem;border-radius:8px;font-size:.88rem}</style></head><body>
<div class="brand"><strong>${COMPANY.name}</strong><span class="m">${COMPANY.tagline}</span></div>
<h1>${esc(name)}</h1>
<p>${esc(dests)} · from ${esc(getDeparture(c.departureId).name)} · ${fmtDate(c.startDate, { day: 'numeric', month: 'long', year: 'numeric' })} · ${c.days} day${c.days > 1 ? 's' : ''} · ${c.adults} adult${c.adults > 1 ? 's' : ''}${c.children ? `, ${c.children} child${c.children > 1 ? 'ren' : ''}` : ''} · ${c.rooms} room${c.rooms > 1 ? 's' : ''}</p>
<div class="note"><strong>Estimated total: ${money(est.total)}</strong> (range ${money(est.low)} – ${money(est.high)}) · ${money(est.perPerson)} per person.<br>
${PRICING_BASIS.label}, compiled ${PRICING_BASIS.compiledOn}. ${PRICING_BASIS.note}</div>
${dayHtml}
<h2>Estimate breakdown</h2><table>${cats}<tr><td>Contingency (${c.contingencyPct}%)</td><td class="c">${money(est.contingency)}</td></tr><tr><td><strong>Total</strong></td><td class="c"><strong>${money(est.total)}</strong></td></tr></table>
<h2>Inclusions</h2><ul>${est.inclusions.map((i) => `<li>${esc(i)}</li>`).join('')}</ul>
<h2>Exclusions</h2><ul>${est.exclusions.map((i) => `<li>${esc(i)}</li>`).join('')}</ul>
<h2>Assumptions</h2><ul>${est.assumptions.map((i) => `<li>${esc(i)}</li>`).join('')}</ul>
<p class="m">Generated by ${COMPANY.name} on ${new Date().toLocaleString('en-GB')}. Timings are planning estimates; confirm opening hours, transport schedules and bookings with providers. This is not a booking, quote or availability confirmation.</p>
</body></html>`;
}

export function download(filename: string, content: string, type = 'text/html') {
  const blob = new Blob([content], { type });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  setTimeout(() => {
    URL.revokeObjectURL(a.href);
    a.remove();
  }, 500);
}

export const fileSafe = (s: string) => s.replace(/[^a-z0-9]+/gi, '-').replace(/(^-|-$)/g, '').toLowerCase();
